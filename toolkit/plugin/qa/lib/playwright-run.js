// Runs Playwright on QA's own runtime: writes a generated config, builds the worker environment (accounts
// and environment base64-encoded, never on a command line) and starts the Playwright CLI with Node directly.
const fs = require('fs');
const path = require('path');
const config = require('../../office/lib/config');
const { libDir } = require('./paths');
const { runtimeEnv, cliFile } = require('./runtime');
const { start } = require('./spawn');

const PLUGIN_DIR = path.join(__dirname, '..', '..');
const encode = (value) => Buffer.from(JSON.stringify(value)).toString('base64');

/** Copies the fixture, reporter and smoke check next to each other in <qaHome>/lib, where specs import them. */
function installLib() {
  const dir = libDir();
  fs.mkdirSync(dir, { recursive: true });
  const qaDir = path.join(PLUGIN_DIR, 'qa');
  fs.copyFileSync(path.join(qaDir, 'fixture.js'), path.join(dir, 'devcrew-qa.js'));
  fs.copyFileSync(path.join(qaDir, 'reporter.js'), path.join(dir, 'devcrew-reporter.js'));
  fs.copyFileSync(path.join(qaDir, 'smoke.spec.js'), path.join(dir, 'smoke.spec.js'));
}

/** The environment for Playwright and its workers. Only labels, usernames and passwords of this environment's accounts. */
function testEnv({ runId, app, environment, accounts, tilePrefix = '', video = false }) {
  return runtimeEnv({
    FORCE_COLOR: '0',
    DEVCREW_HOME: config.dataDir(),
    DEVCREW_OFFICE_PORT: String(config.port()),
    DEVCREW_QA_OFFICE_TOKEN: process.env.DEVCREW_QA_OFFICE_TOKEN || config.token(),
    DEVCREW_QA_PLUGIN_DIR: PLUGIN_DIR,
    DEVCREW_QA_RUN: runId,
    DEVCREW_QA_PROJECT: `QA · ${app.name} · ${environment.name}`,
    DEVCREW_QA_ENV: encode({ id: environment.id, name: environment.name, kind: environment.kind, baseUrl: environment.baseUrl, loginPath: environment.loginPath, login: environment.login }),
    DEVCREW_QA_ACCOUNTS: encode(accounts.map(({ label, username, password }) => ({ label, username, password }))),
    DEVCREW_QA_TILE_PREFIX: tilePrefix,
    DEVCREW_QA_VIDEO: video ? '1' : '0',
  });
}

/** A test file regex for Playwright's testMatch, from file names like "ab12cd34.spec.ts". */
const filesPattern = (names) => `[\\\\/](?:${names.map((name) => name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')).join('|')})$`;

/**
 * Writes <dir>/qa-run.json and <dir>/playwright.config.js. Projects are { name, testDir, files: [names] }.
 * The config is JSON so nothing from a case can become code; the small loader turns patterns into RegExps.
 */
function writeConfig(dir, { projects, workers = 1, reporter, outputDir, artifacts = true }) {
  const settings = {
    timeout: 90000,
    workers,
    retries: 0,
    fullyParallel: true,
    outputDir,
    reporter,
    use: {
      headless: true,
      screenshot: artifacts ? 'only-on-failure' : 'off',
      trace: artifacts ? 'retain-on-failure' : 'off',
      actionTimeout: 15000,
      navigationTimeout: 30000,
    },
    projects: projects.map(({ name, testDir, files }) => ({ name, testDir, testMatch: filesPattern(files) })),
  };
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, 'qa-run.json'), JSON.stringify(settings, null, 2));
  const loader = `// Generated by devcrew QA.\nconst settings = require('./qa-run.json');\nfor (const project of settings.projects) project.testMatch = new RegExp(project.testMatch);\nmodule.exports = settings;\n`;
  const file = path.join(dir, 'playwright.config.js');
  fs.writeFileSync(file, loader);
  return file;
}

/** Starts `playwright test`. Resolves { child, done } where done resolves { code, output } (output: last 16 KB). */
async function runPlaywright(configFile, env) {
  const child = await start(process.execPath, [cliFile(), 'test', '--config', configFile], { cwd: path.dirname(configFile), env, stdio: ['ignore', 'pipe', 'pipe'] });
  let output = '';
  const keep = (chunk) => (output = (output + chunk).slice(-16 * 1024));
  child.stdout.on('data', keep);
  child.stderr.on('data', keep);
  const done = new Promise((resolve) => child.on('close', (code) => resolve({ code, output })));
  return { child, done };
}

/** Every test result in a Playwright JSON report, as { file, title, result }. */
function resultsOf(report) {
  const found = [];
  const walk = (suite) => {
    for (const spec of suite.specs || []) {
      for (const item of spec.tests || []) {
        const result = (item.results || []).at(-1);
        if (result) found.push({ file: path.basename(spec.file || ''), title: spec.title, result });
      }
    }
    (suite.suites || []).forEach(walk);
  };
  (report?.suites || []).forEach(walk);
  return found;
}

const stripAnsi = (text) => String(text || '').replace(/\u001b\[[0-9;]*m/g, '');

/** Replaces every password of these accounts with *** so no message carries one. */
function redactSecrets(text, accounts) {
  let clean = String(text ?? '');
  for (const account of accounts) if (account.password) clean = clean.split(account.password).join('***');
  return clean;
}

module.exports = { PLUGIN_DIR, installLib, testEnv, writeConfig, runPlaywright, resultsOf, stripAnsi, redactSecrets };
