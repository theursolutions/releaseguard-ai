#!/usr/bin/env node
// PreToolUse hook for Edit/Write: stops Claude from changing files that hold secrets,
// third-party code or generated output. Exit code 2 blocks the edit and shows Claude the reason.
const path = require('path');

const PROTECTED = [
  { pattern: /(^|\/)\.env$|(^|\/)\.env\.(?!example$)[^/]+$/, reason: 'environment files hold secrets' },
  { pattern: /\.(pem|key|p12|pfx|crt)$/i, reason: 'certificates and private keys must never be edited by AI' },
  { pattern: /(^|\/)(vendor|node_modules)\//, reason: 'third-party code changes through composer/npm, never by hand' },
  { pattern: /(^|\/)(composer\.lock|package-lock\.json|yarn\.lock|pnpm-lock\.yaml)$/, reason: 'lock files change only through the package manager' },
  { pattern: /(^|\/)public\/(build|vendor)\//, reason: 'compiled assets are generated by the build, edit the source instead' },
  { pattern: /(^|\/)storage\/(logs|framework)\//, reason: 'runtime files are generated by the application' },
  { pattern: /(^|\/)\.git\//, reason: 'git internals must not be edited' },
];

let raw = '';
process.stdin.on('data', (chunk) => (raw += chunk));
process.stdin.on('end', () => {
  let input;
  try {
    input = JSON.parse(raw || '{}');
  } catch {
    process.exit(0);
  }

  const filePath = input.tool_input?.file_path || input.tool_input?.notebook_path;
  if (!filePath) process.exit(0);

  const projectDir = process.env.CLAUDE_PROJECT_DIR || input.cwd || process.cwd();
  const relative = path.relative(projectDir, path.resolve(projectDir, filePath)).split(path.sep).join('/');

  const hit = PROTECTED.find((rule) => rule.pattern.test(relative));
  if (!hit) process.exit(0);

  process.stderr.write(
    `Blocked by team toolkit: "${relative}" is protected (${hit.reason}). ` +
      'Do not try another way to change it. Tell the user what change is needed so they can make it themselves.\n'
  );
  process.exit(2);
});
